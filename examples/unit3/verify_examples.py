def crit(f):
    sol=solve([diff(f,x),diff(f,y)],[x,y],dict=True); out=[]
    for sdict in sol:
        fxx=diff(f,x,2).subs(sdict); fyy=diff(f,y,2).subs(sdict); fxy=diff(f,x,y).subs(sdict)
        out.append((sdict, 'D=%s'%(fxx*fyy-fxy**2), 'fxx=%s'%fxx, 'f=%s'%f.subs(sdict)))
    return out
